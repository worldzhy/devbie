import path from "node:path";

import prettier from "prettier";

import { MODULES_CONFIG_TS, MODULES_MODULE_TS } from "../constants/paths";
import { collectEnvReferences, moduleImportLine, ModuleManifest } from "../core/module-manifest";
import { IssueBag, reportIssue } from "../lib/issues";
import { readInstalledManifest } from "../lib/module-install";
import { Sink } from "../lib/sink";

const DO_NOT_EDIT_HEADER = `// THIS FILE IS GENERATED BY @devbie/newbie-cli. DO NOT EDIT.
// Run 'newbie modules apply' to regenerate this file.

`;

const EMPTY_MODULE_TEMPLATE = `${DO_NOT_EDIT_HEADER}import {Global, Module} from '@nestjs/common';

@Global()
@Module({
  imports: [],
})
export class ModulesModule {}
`;

const EMPTY_CONFIG_TEMPLATE = `${DO_NOT_EDIT_HEADER}import {registerAs} from '@nestjs/config';

export default registerAs('modules', () => ({}));
`;

function moduleTemplate(entries: { key: string; manifest: ModuleManifest }[]): string {
  const hasConfigService = entries.length > 0;
  const importCode = [
    `import {Global, Module} from '@nestjs/common';`,
    hasConfigService
      ? `import ModulesConfiguration from './modules.config';\nimport {ConfigModule} from '@nestjs/config';`
      : "",
    ...entries.map(({ key, manifest }) => moduleImportLine(key, manifest)),
  ]
    .filter(Boolean)
    .join("\n");

  const importModuleNames = [
    hasConfigService ? `ConfigModule.forRoot({load: [ModulesConfiguration], isGlobal: true})` : "",
    ...entries.map(({ manifest }) => manifest.module.className),
  ]
    .filter(Boolean)
    .join(",\n    ");

  return `${DO_NOT_EDIT_HEADER}${importCode}

@Global()
@Module({
  imports: [
    ${importModuleNames}
  ],
})
export class ModulesModule {}
`;
}

/** Runtime expressions the generator is able to unwrap into real code. */
const RUNTIME_EXPRESSION = /^process\.env\.[A-Za-z_][A-Za-z0-9_]*$/;

/** Strings that intend to be runtime expressions, not literal values. */
const RUNTIME_EXPRESSION_INTENT = /^(?:process\.|bool\(|int\()/;

/**
 * Manifest config values are emitted by string substitution, so a value such
 * as "process.env.X || 'fallback'" (quotes inside the string) is not unwrapped.
 * Reject it loudly: silently embedding it as a string literal was how a
 * fallback-shaped expression once became an always-true config value.
 *
 * Only a bare reference is accepted: helper calls such as int(process.env.X)
 * cannot be emitted with a valid arity (both helpers take a mandatory default),
 * and defaults are exactly the fallbacks ADR-033 forbids in the manifest.
 */
function assertUnwrappableExpressions(value: unknown, path: string): void {
  if (typeof value === "string") {
    if (RUNTIME_EXPRESSION_INTENT.test(value) && !RUNTIME_EXPRESSION.test(value)) {
      throw new Error(
        `${path} looks like a runtime expression but cannot be unwrapped: ${value}. ` +
          `Use a bare 'process.env.NAME'; fallbacks and type coercion belong in module code (ADR-033).`,
      );
    }
    return;
  }
  if (Array.isArray(value)) {
    value.forEach((item, index) => assertUnwrappableExpressions(item, `${path}[${index}]`));
    return;
  }
  if (value && typeof value === "object") {
    for (const [key, item] of Object.entries(value)) {
      assertUnwrappableExpressions(item, `${path}.${key}`);
    }
  }
}

/**
 * Warn about env keys the module declares but its config-service never reads:
 * the deployment contract would carry a variable that no code consumes, which
 * is either a leftover or a misnamed reference (ADR-033).
 */
function reportUnusedEnvKeys(manifest: ModuleManifest, issues: IssueBag, sink: Sink): void {
  const referenced = collectEnvReferences(manifest["config-service"] ?? {});
  const unused = Object.keys(manifest.env ?? {}).filter((name) => !referenced.has(name));
  if (unused.length === 0) return;
  reportIssue(
    issues,
    sink,
    `${manifest.key}: env variable(s) never read by config-service: ${unused.join(", ")}. ` +
      `Declare only the keys the module consumes (ADR-033).`,
  );
}

function configTemplate(configs: Record<string, unknown>): string {
  // The manifest stores runtime expressions as plain strings ("process.env.X");
  // unwrap the quotes so they become real TS expressions in the generated file.
  // The `process.` requirement keeps ordinary strings such as "process-mode"
  // from being turned into (invalid) code.
  const body = JSON.stringify(configs, null, 2).replace(/("|')(process\.[^"']*?)\1/g, "$2");

  return `${DO_NOT_EDIT_HEADER}import {registerAs} from '@nestjs/config';

export default registerAs('modules', () => (${body}));
`;
}

/**
 * Format a generated file with the project's prettier configuration. Formatting
 * happens in memory so `--check` compares the same bytes a write would produce;
 * running prettier as a separate command made check mode always report drift.
 */
async function formatGeneratedFile(cwd: string, file: string, content: string): Promise<string> {
  const filepath = path.resolve(cwd, file);
  const options = (await prettier.resolveConfig(filepath)) ?? {};
  return prettier.format(content, { ...options, filepath, parser: "typescript" });
}

export async function assembleNestJsModules(params: {
  cwd: string;
  sink: Sink;
  issues: IssueBag;
  enabledKeys: string[];
}): Promise<void> {
  const { cwd, sink, issues, enabledKeys } = params;

  const entries: { key: string; manifest: ModuleManifest }[] = [];
  for (const key of enabledKeys) {
    const manifest = await readInstalledManifest(cwd, key);
    if (manifest === null) {
      reportIssue(issues, sink, `Missing newbie.module.json for '${key}'; it was skipped in the NestJS module wiring.`);
      continue;
    }
    entries.push({ key, manifest });
  }

  await sink.writeText(
    MODULES_MODULE_TS,
    await formatGeneratedFile(
      cwd,
      MODULES_MODULE_TS,
      entries.length > 0 ? moduleTemplate(entries) : EMPTY_MODULE_TEMPLATE,
    ),
  );

  let configs: Record<string, unknown> = {};
  for (const { key, manifest } of entries) {
    const manifestConfigs = manifest["config-service"] ?? {};
    assertUnwrappableExpressions(manifestConfigs, `${key}: config-service`);
    reportUnusedEnvKeys(manifest, issues, sink);
    configs = { ...configs, ...manifestConfigs };
  }

  await sink.writeText(
    MODULES_CONFIG_TS,
    await formatGeneratedFile(
      cwd,
      MODULES_CONFIG_TS,
      Object.keys(configs).length > 0 ? configTemplate(configs) : EMPTY_CONFIG_TEMPLATE,
    ),
  );
}
