/**
 * Pure renderer for deploy/compose.modules.yml (ADR-008 D1): the
 * assemble-owned compose layer holding every module-derived service.
 *
 * Input is the enabled datastore modules plus whether each ships a migrator
 * (convention: src/modules/<key>/migration/migrate-cli.ts, compiled to
 * dist/src/modules/<key>/migration/migrate-cli.js). Every runtime value comes
 * from DATASTORE_REGISTRY — nothing is read from module manifests.
 *
 * The YAML is emitted by a tiny hand-rolled writer (zero dependencies, same
 * stance as core/unified-diff.ts): block maps/lists at indent 2, and every
 * string scalar JSON-double-quoted (JSON is a subset of YAML flow
 * double-quoted scalars; quoting also kills the YAML 1.1 boolean trap for
 * restart: "no" and --appendonly "yes"). Byte stability is pinned by golden
 * tests; `docker compose config` normalisation is the equivalence evidence
 * against the incumbent hand-written stack.
 */

import { compareStrings } from "./env-file";
import { ComposeServiceSpec, DATASTORE_REGISTRY, isRegisteredDatastore } from "./datastore-registry";

/** A datastore module enabled in the consuming project. */
export interface ComposeModulesInput {
  key: string;
  /** Convention probe: src/modules/<key>/migration/migrate-cli.ts exists. */
  hasMigrator: boolean;
}

const HEADER = `# THIS FILE IS GENERATED BY @devbie/newbie-cli. DO NOT EDIT.
# Regenerate with \`newbie modules apply\` (it also runs as part of modules update).

`;

const EMPTY_YAML = `${HEADER}services: {}\n`;

function quote(value: string): string {
  return JSON.stringify(value);
}

/** Bare keys for simple names; JSON-quoted when special chars appear. */
function emitKey(key: string): string {
  return /^[A-Za-z0-9_-]+$/.test(key) ? key : quote(key);
}

/** Flow list, matching the incumbent file's command/profiles/test style. */
function flowList(items: string[]): string {
  return `[${items.map(quote).join(", ")}]`;
}

function blockList(indent: string, items: string[]): string[] {
  return items.map((item) => `${indent}- ${quote(item)}`);
}

/** Render one service body at the two-space `services:` indent. */
function emitService(name: string, spec: ComposeServiceSpec, labels?: Record<string, string>): string[] {
  const lines: string[] = [`  ${name}:`];
  lines.push(`    image: ${quote(spec.image)}`);
  if (spec.restart) lines.push(`    restart: ${quote(spec.restart)}`);
  if (spec.command) lines.push(`    command: ${flowList(spec.command)}`);
  if (spec.profiles) lines.push(`    profiles: ${flowList(spec.profiles)}`);
  if (spec.envFile) lines.push(`    env_file:`, `      - "./.env"`);
  if (spec.environment) {
    lines.push(`    environment:`);
    for (const [key, value] of Object.entries(spec.environment)) {
      lines.push(`      ${emitKey(key)}: ${quote(value)}`);
    }
  }
  if (spec.ulimits) {
    lines.push(`    ulimits:`);
    for (const [key, value] of Object.entries(spec.ulimits)) {
      lines.push(`      ${emitKey(key)}:`, `        soft: ${quote(value.soft)}`, `        hard: ${quote(value.hard)}`);
    }
  }
  if (spec.volumes) lines.push(`    volumes:`, ...blockList("      ", spec.volumes));
  // Every service joins the framework-owned internal network defined in
  // compose.framework.yml; only caddy publishes host ports.
  lines.push(`    networks:`, `      - "nwb"`);
  if (labels) {
    lines.push(`    labels:`);
    for (const [key, value] of Object.entries(labels)) {
      lines.push(`      ${emitKey(key)}: ${quote(value)}`);
    }
  }
  if (spec.healthcheck) {
    const healthcheck = spec.healthcheck;
    lines.push(
      `    healthcheck:`,
      `      test: ${flowList(healthcheck.test)}`,
      `      interval: ${quote(healthcheck.interval)}`,
      `      timeout: ${quote(healthcheck.timeout)}`,
      `      retries: ${healthcheck.retries}`,
    );
  }
  if (spec.dependsOn) {
    lines.push(`    depends_on:`);
    for (const [key, value] of Object.entries(spec.dependsOn)) {
      lines.push(`      ${emitKey(key)}:`, `        condition: ${quote(value.condition)}`);
    }
  }
  return lines;
}

/**
 * One-shot forward-only migration runner, mirroring the postgres-migrate
 * convention: backend starts only after this exits successfully.
 */
function migratorSpec(key: string): ComposeServiceSpec {
  return {
    image: "${ECR_REPOSITORY_PREFIX}/${APP_NAME}-backend:${IMAGE_TAG}",
    restart: "no",
    envFile: true,
    command: ["node", `dist/src/modules/${key}/migration/migrate-cli.js`, "deploy"],
    dependsOn: { [key]: { condition: "service_healthy" } },
  };
}

/**
 * Render the full compose.modules.yml document. Service groups are sorted by
 * module key; within a group the order is main service, `<key>-backup`,
 * `<key>-migrate`. The backend fragment carries only module-derived
 * depends_on entries (migrators first, then healthy services), which docker
 * compose merges with the framework layer's own depends_on (ADR-008 D1
 * verified merge semantics).
 */
export function buildComposeModulesYaml(datastores: ComposeModulesInput[]): string {
  for (const { key } of datastores) {
    if (!isRegisteredDatastore(key)) {
      throw new Error(`compose.modules.yml renderer: '${key}' is not listed in the datastore registry`);
    }
  }
  const sorted = [...datastores].sort((a, b) => compareStrings(a.key, b.key));

  const serviceLines: string[] = [];
  const healthyServices: string[] = [];
  const migratorServices: string[] = [];
  for (const { key, hasMigrator } of sorted) {
    const definition = DATASTORE_REGISTRY[key];
    if (!definition.service) continue;
    const labels = definition.backupEngine ? { "newbie.backup-engine": definition.backupEngine } : undefined;
    serviceLines.push(...emitService(key, definition.service, labels));
    healthyServices.push(key);
    if (definition.backupHelper) {
      serviceLines.push(...emitService(`${key}-backup`, definition.backupHelper));
    }
    if (hasMigrator) {
      serviceLines.push(...emitService(`${key}-migrate`, migratorSpec(key)));
      migratorServices.push(`${key}-migrate`);
    }
  }

  if (serviceLines.length === 0) return EMPTY_YAML;

  const lines: string[] = [`${HEADER}services:`, ...serviceLines];
  lines.push("  backend:", "    depends_on:");
  for (const service of migratorServices) {
    lines.push(`      ${service}:`, `        condition: "service_completed_successfully"`);
  }
  for (const service of healthyServices) {
    lines.push(`      ${service}:`, `        condition: "service_healthy"`);
  }
  return `${lines.join("\n")}\n`;
}
