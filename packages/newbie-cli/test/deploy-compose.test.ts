describe("buildComposeModulesYaml", () => {
  it("renders the full golden document (byte stability)", () => {
    const yaml = buildComposeModulesYaml([
      { key: "mongo", hasMigrator: false },
      { key: "redis", hasMigrator: false },
      { key: "clickhouse", hasMigrator: true },
    ]);
    assert.equal(yaml, FULL_GOLDEN);
  });

  it("is idempotent regardless of input order", () => {
    const a = buildComposeModulesYaml([
      { key: "mongo", hasMigrator: false },
      { key: "redis", hasMigrator: false },
      { key: "clickhouse", hasMigrator: true },
    ]);
    const b = buildComposeModulesYaml([
      { key: "redis", hasMigrator: false },
      { key: "clickhouse", hasMigrator: true },
      { key: "mongo", hasMigrator: false },
    ]);
    assert.equal(a, b);
  });

  it("renders an empty services map when nothing is enabled", () => {
    assert.equal(buildComposeModulesYaml([]), `${HEADER}services: {}\n`);
  });

  it("renders an empty services map for service-less datastores (no deployment precedent)", () => {
    // A migrator without a main service makes no sense and is not rendered.
    assert.equal(buildComposeModulesYaml([{ key: "elasticsearch", hasMigrator: true }]), `${HEADER}services: {}\n`);
  });

  it("quotes the YAML 1.1 boolean traps verbatim", () => {
    const yaml = buildComposeModulesYaml([
      { key: "redis", hasMigrator: false },
      { key: "clickhouse", hasMigrator: true },
    ]);
    // restart: no and --appendonly yes must stay strings, never booleans.
    assert.match(yaml, /restart: "no"/);
    assert.match(yaml, /"--appendonly", "yes"/);
  });

  it("omits the migrator when the module ships no migration CLI", () => {
    const yaml = buildComposeModulesYaml([{ key: "clickhouse", hasMigrator: false }]);
    assert.ok(!yaml.includes("clickhouse-migrate"));
    assert.ok(!yaml.includes("service_completed_successfully"));
  });

  it("rejects a datastore key missing from the registry", () => {
    assert.throws(
      () => buildComposeModulesYaml([{ key: "vault", hasMigrator: false }]),
      /not listed in the datastore registry/,
    );
  });
});
