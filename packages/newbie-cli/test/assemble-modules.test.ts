import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, it } from "node:test";

import { assembleNestJsModules } from "../src/assemble/modules";
import { IssueBag } from "../src/lib/issues";
import { createSink } from "../src/lib/sink";

const directories: string[] = [];

async function makeProject(modules: Record<string, Record<string, unknown>>): Promise<string> {
  const cwd = await fs.mkdtemp(path.join(os.tmpdir(), "newbie-assemble-modules-"));
  directories.push(cwd);
  for (const [key, extra] of Object.entries(modules)) {
    const dir = path.join(cwd, "src", "modules", key);
    await fs.mkdir(dir, { recursive: true });
    await fs.writeFile(
      path.join(dir, "newbie.module.json"),
      JSON.stringify({ key, module: { file: `${key}.module`, className: `${key}Module` }, ...extra }),
      "utf8",
    );
  }
  return cwd;
}

async function assemble(
  cwd: string,
  enabledKeys: string[],
  options: { check?: boolean } = {},
): Promise<{ issues: IssueBag; sink: ReturnType<typeof createSink> }> {
  const issues = new IssueBag();
  const sink = createSink(cwd, false, options);
  await assembleNestJsModules({ cwd, sink, issues, enabledKeys });
  return { issues, sink };
}

async function readOut(cwd: string, file: string): Promise<string> {
  return fs.readFile(path.join(cwd, file), "utf8");
}

afterEach(async () => {
  await Promise.all(directories.splice(0).map((dir) => fs.rm(dir, { recursive: true, force: true })));
});

describe("assembleNestJsModules", () => {
  it("wires every enabled module into the global ModulesModule", async () => {
    const cwd = await makeProject({
      account: {},
      audit: { moduleDependencies: ["security"] },
      security: {},
    });

    const { issues } = await assemble(cwd, ["account", "audit", "security"]);

    assert.equal(issues.count, 0);
    const wiring = await readOut(cwd, "src/modules/modules.module.ts");
    assert.match(wiring, /^\/\/ THIS FILE IS GENERATED BY @devbie\/newbie-cli/);
    assert.match(wiring, /import \{ accountModule \} from "\.\/account\/account\.module";/);
    assert.match(wiring, /import \{ auditModule \} from "\.\/audit\/audit\.module";/);
    assert.match(wiring, /import \{ securityModule \} from "\.\/security\/security\.module";/);
    assert.match(wiring, /ConfigModule\.forRoot\(\{ load: \[ModulesConfiguration\], isGlobal: true \}\)/);
    assert.match(wiring, /accountModule,\n {4}auditModule,\n {4}securityModule/);
  });

  it("emits the empty templates when no module is enabled", async () => {
    const cwd = await makeProject({});

    const { issues } = await assemble(cwd, []);

    assert.equal(issues.count, 0);
    assert.match(await readOut(cwd, "src/modules/modules.module.ts"), /imports: \[\]/);
    assert.match(await readOut(cwd, "src/modules/modules.config.ts"), /registerAs\("modules", \(\) => \(\{\}\)\)/);
  });

  it("renders module config services as real expressions with the right helpers", async () => {
    const cwd = await makeProject({
      account: {
        "config-service": {
          FEATURE_FLAG: "bool(process.env.FEATURE_FLAG)",
          PORT: "int(process.env.PORT)",
          NAME: "account",
        },
      },
    });

    await assemble(cwd, ["account"]);

    const config = await readOut(cwd, "src/modules/modules.config.ts");
    assert.match(config, /import \{ bool, int \} from "@devbie\/newbie";/);
    assert.match(config, /FEATURE_FLAG: bool\(process\.env\.FEATURE_FLAG\)/);
    assert.match(config, /PORT: int\(process\.env\.PORT\)/);
    assert.match(config, /NAME: "account"/);
  });

  it("reports no drift when the written files are checked again", async () => {
    const cwd = await makeProject({ account: {} });

    const written = await assemble(cwd, ["account"]);
    assert.equal(written.issues.count, 0);

    const checked = await assemble(cwd, ["account"], { check: true });

    assert.equal(checked.issues.count, 0);
    assert.deepEqual(checked.sink.findings, []);
  });

  it("reports modules whose copied manifest is missing and skips them", async () => {
    const cwd = await makeProject({ account: {} });

    const { issues } = await assemble(cwd, ["account", "ghost"]);

    assert.equal(issues.count, 1);
    const wiring = await readOut(cwd, "src/modules/modules.module.ts");
    assert.match(wiring, /accountModule/);
    assert.doesNotMatch(wiring, /ghostModule/);
  });
});
